/* ScopeSnap report preview. Original app-exported WebP pages, never public PDFs.
   One page visible at a time; page changes are horizontal, not continuous scroll. */
(() => {
  "use strict";
  const root=document.getElementById("reports");
  const frame=document.getElementById("rv");
  if(!root||!frame)return;

  const tabs=[...root.querySelectorAll(".so-report-option")];
  const counter=document.getElementById("rv-current");
  const caption=document.getElementById("rv-caption");
  const previous=document.getElementById("rv-prev");
  const next=document.getElementById("rv-next");
  const motion=window.matchMedia("(prefers-reduced-motion: reduce)");
  const FIRST_DELAY=5500;
  const TURN_DURATION=480;

  let manifest=null,selected="client",index=0;
  let visible=false,hydrated=false,hovered=false,held=false,focused=false,turning=false;
  let timer=null,swapTimeout=null,liveImage=document.getElementById("rv-page");
  let requestId=0,swipeStart=null;

  function pages(type){return manifest?.[type]?.imageInfo||[];}
  function pageUrl(type,idx){
    return "/images/reports/"+encodeURIComponent(pages(type)[idx].file)+
      "?v="+encodeURIComponent(manifest.version);
  }
  function allowAuto(){
    return !!manifest&&visible&&!hovered&&!held&&!focused&&!motion.matches&&!document.hidden;
  }
  function stopTimer(){if(timer!==null){clearTimeout(timer);timer=null;}}
  function schedule(){
    stopTimer();
    if(allowAuto()&&!turning)timer=setTimeout(()=>goTo(index+1),FIRST_DELAY);
  }
  function preload(type,idx){
    if(!visible||!manifest||!pages(type).length)return;
    const probe=new Image();
    probe.decoding="async";probe.src=pageUrl(type,(idx+pages(type).length)%pages(type).length);
  }
  function displayMeta(){
    const item=manifest[selected];
    counter.textContent="PAGE "+(index+1)+" OF "+item.pages;
    caption.textContent=selected.toUpperCase()+" REPORT · "+item.pages+" PAGES · GENERATED BY SCOPESNAP";
    frame.setAttribute("aria-label",(selected==="client"?"Client":"Internal")+" report page "+(index+1)+" of "+item.pages);
    frame.setAttribute("aria-labelledby","rv-tab-"+selected);
  }
  function updateSelection(){
    tabs.forEach(tab=>{
      const active=tab.dataset.name===selected;
      tab.setAttribute("aria-selected",String(active));
      tab.tabIndex=active?0:-1;
    });
    // Both audience descriptions stay visible; only active styling changes.
  }
  function imageFor(type,idx){
    const item=pages(type)[idx],image=document.createElement("img");
    image.className="rv-page rv-coming";
    image.alt=item.alt||type+" report page "+(idx+1);
    image.width=item.width||1310;image.height=item.height||1853;
    image.decoding="async";image.src=pageUrl(type,idx);
    return image;
  }
  function goTo(target,{instant=false}={}){
    if(!manifest||turning)return;
    const list=pages(selected);if(!list.length)return;
    const to=(target+list.length)%list.length;
    stopTimer();
    if(to===index){schedule();return;}
    const source=selected,id=++requestId;
    const incoming=imageFor(source,to);
    turning=true;
    const reveal=()=>{
      if(id!==requestId||selected!==source)return;
      if(instant||motion.matches){
        liveImage.replaceWith(incoming);
        incoming.className="rv-page";incoming.id="rv-page";
        liveImage=incoming;index=to;displayMeta();turning=false;
        preload(selected,index+1);schedule();return;
      }
      liveImage.removeAttribute("id");
      liveImage.classList.add("rv-leaving");
      incoming.setAttribute("aria-hidden","true");
      frame.append(incoming);
      requestAnimationFrame(()=>incoming.classList.add("rv-arrived"));
      swapTimeout=setTimeout(()=>{
        if(id!==requestId)return;
        liveImage.remove();
        incoming.id="rv-page";incoming.className="rv-page";
        incoming.removeAttribute("aria-hidden");
        liveImage=incoming;index=to;displayMeta();turning=false;
        preload(selected,index+1);schedule();
      },TURN_DURATION+35);
    };
    if(incoming.complete&&incoming.naturalWidth)reveal();
    else{
      incoming.addEventListener("load",reveal,{once:true});
      incoming.addEventListener("error",()=>{
        if(id!==requestId)return;
        turning=false;schedule();
      },{once:true});
    }
  }
  function selectReport(type){
    if(!manifest?.[type])return;
    hydrated=true;
    stopTimer();
    requestId++;
    if(swapTimeout!==null){clearTimeout(swapTimeout);swapTimeout=null;}
    // Remove any outgoing or incomplete incoming image from the old report.
    frame.querySelectorAll(".rv-page").forEach(img=>{if(img!==liveImage)img.remove();});
    liveImage.classList.remove("rv-leaving");
    liveImage.id="rv-page";
    turning=false;selected=type;index=0;
    const first=imageFor(type,0);
    first.className="rv-page";first.id="rv-page";
    liveImage.replaceWith(first);liveImage=first;
    updateSelection();displayMeta();
    preload(type,1);schedule();
  }
  tabs.forEach(tab=>{
    tab.addEventListener("click",()=>selectReport(tab.dataset.name));
    tab.addEventListener("keydown",event=>{
      if(event.key!=="ArrowLeft"&&event.key!=="ArrowRight")return;
      event.preventDefault();
      const at=tabs.indexOf(tab),direction=event.key==="ArrowRight"?1:-1;
      const tabTo=tabs[(at+direction+tabs.length)%tabs.length];
      tabTo.focus();selectReport(tabTo.dataset.name);
    });
  });
  previous.addEventListener("click",()=>goTo(index-1));
  next.addEventListener("click",()=>goTo(index+1));

  // Pointer swiping retains native vertical page scrolling.
  frame.addEventListener("pointerdown",event=>{
    if(event.pointerType==="mouse")return;
    swipeStart={x:event.clientX,y:event.clientY};
    held=true;stopTimer();
  });
  frame.addEventListener("pointerup",event=>{
    if(event.pointerType==="mouse")return;
    const from=swipeStart;swipeStart=null;held=false;
    if(from){
      const dx=event.clientX-from.x,dy=event.clientY-from.y;
      if(Math.abs(dx)>=38&&Math.abs(dx)>Math.abs(dy)*1.3){
        goTo(index+(dx<0?1:-1));return;
      }
    }
    schedule();
  });
  frame.addEventListener("pointercancel",()=>{held=false;swipeStart=null;schedule();});
  frame.addEventListener("pointerenter",event=>{if(event.pointerType==="mouse"){hovered=true;stopTimer();}});
  frame.addEventListener("pointerleave",event=>{if(event.pointerType==="mouse"){hovered=false;schedule();}});
  // Pause for keyboard focus, but not permanently after a mouse clicks
  // a report tab: pointer users should still see automatic page changes.
  root.addEventListener("focusin",()=>{
    focused=!!root.querySelector(":focus-visible");
    if(focused)stopTimer();else schedule();
  });
  root.addEventListener("focusout",()=>{
    focused=!!root.querySelector(":focus-visible");
    schedule();
  });
  frame.addEventListener("keydown",event=>{
    if(event.key!=="ArrowRight"&&event.key!=="ArrowLeft")return;
    event.preventDefault();goTo(index+(event.key==="ArrowRight"?1:-1));
  });
  document.addEventListener("visibilitychange",schedule);
  motion.addEventListener?.("change",schedule);
  if("IntersectionObserver" in window){
    new IntersectionObserver(entries=>{
      visible=entries[0]?.isIntersecting||false;
      if(visible){if(manifest&&!hydrated)selectReport(selected);preload(selected,index+1);}
      schedule();
    },{threshold:0.05}).observe(root);
  }else visible=true;

  fetch("/images/reports/manifest.json",{cache:"no-cache"})
    .then(response=>{if(!response.ok)throw new Error("Report images unavailable");return response.json();})
    .then(data=>{
      for(const type of ["client","internal"]){
        if(!data[type]||data[type].files.length!==data[type].pages||
           !data[type].imageInfo?.length)throw new Error("Incomplete "+type+" report pages");
      }
      manifest=data;
      // Do not download report pages miles below the fold. Hydrate once visible.
      if(visible)selectReport("client");
      else{updateSelection();displayMeta();}
      frame.classList.add("rv-loaded");
    })
    .catch(error=>{
      console.warn("Report preview could not initialise:",error.message);
      frame.classList.add("rv-fallback-mode");
      caption.textContent="REPORT PREVIEW TEMPORARILY UNAVAILABLE";
      tabs.forEach(tab=>{if(tab.dataset.name!=="client")tab.disabled=true;});
    });
})();
