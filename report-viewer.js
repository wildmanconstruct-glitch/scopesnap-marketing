/* Real ScopeSnap report-image showcase. The only public media is WebP.
   PDF creation stays within the private app's jsPDF export pipeline. */
(() => {
  "use strict";
  const section=document.getElementById("reports");
  const frame=document.getElementById("rv");
  if(!section||!frame)return;
  const tabs=[...section.querySelectorAll(".so-report-option")];
  const caption=document.getElementById("rv-caption");
  const previous=document.getElementById("rv-prev");
  const next=document.getElementById("rv-next");
  const status=document.getElementById("rv-current");
  const motion=window.matchMedia("(prefers-reduced-motion: reduce)");
  let manifest=null,selected="client",track=null,manual=null,pageIndex=1;
  let isVisible=false,isNear=false,prepared=new Map(),switching=false;

  function pageItems(kind) {
    const item=manifest?.[kind];
    return item?.imageInfo?.length ? item.imageInfo :
      (item?.files||[]).map(name=>({file:name,width:1310,height:1853,alt:kind+" report page"}));
  }
  function makeImage(kind,page,index,duplicate=false) {
    const img=document.createElement("img");
    img.width=page.width||1310;img.height=page.height||1853;
    img.alt=duplicate ? "" : (page.alt||kind+" report page "+(index+1));
    if(duplicate)img.setAttribute("aria-hidden","true");
    const version=encodeURIComponent(manifest.version||"app-export");
    const url="/images/reports/"+encodeURIComponent(page.file)+"?v="+version;
    img.dataset.src=url;
    if(index<2){img.src=url;img.loading="eager";img.decoding="async";}
    else {img.loading="lazy";img.decoding="async";}
    return img;
  }
  function build(kind) {
    if(prepared.has(kind))return prepared.get(kind);
    const pages=pageItems(kind),outer=document.createElement("div");
    outer.setAttribute("aria-hidden","true");
    outer.className="rv-track";outer.style.setProperty("--loop",(pages.length*4)+"s");
    for(let copy=0;copy<2;copy++){
      const group=document.createElement("div");
      group.className="rv-set";group.setAttribute("aria-hidden",copy?"true":"false");
      pages.forEach((item,i)=>group.append(makeImage(kind,item,i,copy>0)));
      outer.append(group);
    }
    prepared.set(kind,outer);
    return outer;
  }
  function populateRest(kind) {
    const root=prepared.get(kind);
    if(!root)return;
    root.querySelectorAll("img[data-src]:not([src])").forEach(img=>{img.src=img.dataset.src;});
  }
  function setManualPage(kind,index) {
    const pages=pageItems(kind);if(!pages.length)return;
    pageIndex=(index+pages.length)%pages.length;
    const page=pages[pageIndex],version=encodeURIComponent(manifest.version||"app-export");
    if(!manual){
      manual=document.createElement("img");
      manual.className="rv-manual";manual.id="rv-manual";frame.append(manual);
    }
    manual.src="/images/reports/"+encodeURIComponent(page.file)+"?v="+version;
    manual.width=page.width||1310;manual.height=page.height||1853;
    manual.alt=page.alt||kind+" report page "+(pageIndex+1);
    if(status)status.textContent=(pageIndex+1)+" / "+pages.length;
  }
  function activate(kind,automated=false) {
    if(!manifest?.[kind]||switching)return;
    switching=true;
    selected=kind;
    tabs.forEach(tab=>tab.setAttribute("aria-selected",String(tab.dataset.name===kind)));
    const old=track;
    track=build(kind);
    if(old&&old!==track)old.remove();
    if(!track.isConnected)frame.prepend(track);
    // DOM re-entry starts every new selection at page 1.
    track.style.animation="none";void track.offsetHeight;track.style.animation="";
    frame.classList.remove("rv-reveal");void frame.offsetHeight;frame.classList.add("rv-reveal");
    setManualPage(kind,1); // Static reduced-motion view opens on first room page.
    const pages=pageItems(kind).length;
    caption.textContent=kind.toUpperCase()+" REPORT · "+pages+" PAGES · GENERATED BY SCOPESNAP";
    if(isNear||automated)populateRest(kind);
    frame.classList.toggle("rv-active",isVisible&&!motion.matches);
    window.setTimeout(()=>{switching=false;frame.classList.remove("rv-reveal");},305);
  }
  tabs.forEach(tab=>tab.addEventListener("click",()=>activate(tab.dataset.name)));
  frame.addEventListener("animationiteration",e=>{
    if(e.target===track&&!motion.matches&&isVisible&&!frame.classList.contains("rv-held")){
      activate(selected==="client"?"internal":"client",true);
    }
  });
  frame.addEventListener("pointerdown",e=>{if(e.pointerType!=="mouse")frame.classList.add("rv-held");});
  frame.addEventListener("keydown",e=>{if(e.key===" "){e.preventDefault();frame.classList.add("rv-held");}});
  frame.addEventListener("keyup",e=>{if(e.key===" ")frame.classList.remove("rv-held");});
  ["pointerup","pointercancel","pointerleave"].forEach(type=>frame.addEventListener(type,()=>frame.classList.remove("rv-held")));
  previous?.addEventListener("click",()=>setManualPage(selected,pageIndex-1));
  next?.addEventListener("click",()=>setManualPage(selected,pageIndex+1));
  function syncMotion(){
    frame.classList.toggle("rv-paused",motion.matches);
    frame.classList.toggle("rv-active",isVisible&&!motion.matches);
    // CSS alone owns pause state so hover and touch hold override playback.
  }
  motion.addEventListener?.("change",syncMotion);
  new IntersectionObserver(entries=>{
    isVisible=entries[0]?.isIntersecting||false;syncMotion();
  },{threshold:0.02}).observe(section);
  new IntersectionObserver(entries=>{
    if(entries[0]?.isIntersecting){
      isNear=true;populateRest(selected);
    }
  },{rootMargin:"600px 0px"}).observe(section);
  fetch("/images/reports/manifest.json",{cache:"no-cache"})
    .then(response=>{if(!response.ok)throw new Error("Report image manifest missing");return response.json();})
    .then(data=>{
      if(!data.client?.files?.length||!data.internal?.files?.length)throw new Error("No report page images");
      manifest=data;activate("client");syncMotion();
      if(isNear)populateRest("client");
      // Keep a real, static report image visible until the animated stack's
      // first page has actually decoded. Never show an empty white frame.
      const first=frame.querySelector(".rv-set:first-child img[src]");
      const ready=()=>frame.classList.add("rv-loaded");
      if(first?.complete&&first.naturalWidth>0)ready();
      else first?.addEventListener("load",ready,{once:true});
    })
    .catch(error=>{
      console.warn("Report previews unavailable:",error.message);
      frame.classList.add("rv-fallback-mode");
      const fallback=frame.querySelector(".rv-fallback");
      if(fallback)fallback.hidden=false;
      caption.textContent="CLIENT AND INTERNAL REPORT PREVIEWS";
      tabs.forEach(tab=>tab.addEventListener("click",()=>{
        const img=frame.querySelector(".rv-fallback");
        if(img)img.src=tab.dataset.src;
        tabs.forEach(b=>b.setAttribute("aria-selected",String(b===tab)));
      }));
    });
})();
